/// iPad のハードウェアキーボードが報告する USB HID usage を、macOS の仮想キーコード (kVK_*) に変換する。
public enum KeyboardMapping {
    public static func macVirtualKeyCode(forHIDUsage usage: Int) -> UInt16? {
        table[usage]
    }

    public static func isModifier(macVirtualKeyCode keyCode: UInt16) -> Bool {
        (0x36 ... 0x3E).contains(keyCode)
    }

    /// 実際の Mac のキーボードと同じ CGEventFlags の生の値。Control+矢印の Mission Control などは、矢印に Fn とテンキーのビットがないと反応しない。
    public static func eventFlags(modifiers: KeyModifiers, macVirtualKeyCode keyCode: UInt16) -> UInt64 {
        // 下位ビットは左右どちらの修飾キーかを示す (IOLLEvent.h の NX_DEVICE*KEYMASK)。iPad からは左右の区別が届かないので左として扱う
        var flags: UInt64 = 0x100
        if modifiers.contains(.shift) { flags |= 0x20000 | 0x2 }
        if modifiers.contains(.control) { flags |= 0x40000 | 0x1 }
        if modifiers.contains(.option) { flags |= 0x80000 | 0x20 }
        if modifiers.contains(.command) { flags |= 0x100000 | 0x8 }
        if arrowKeys.contains(keyCode) {
            flags |= 0x200000 | 0x800000
        } else if functionKeys.contains(keyCode) {
            flags |= 0x800000
        } else if keypadKeys.contains(keyCode) {
            flags |= 0x200000
        }
        return flags
    }

    private static let arrowKeys: Set<UInt16> = [0x7B, 0x7C, 0x7D, 0x7E]
    // F1〜F20、Help、Home、End、Page Up/Down、Forward Delete
    private static let functionKeys: Set<UInt16> = [
        0x7A, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6D, 0x67, 0x6F,
        0x69, 0x6B, 0x71, 0x6A, 0x40, 0x4F, 0x50, 0x5A,
        0x72, 0x73, 0x77, 0x74, 0x79, 0x75,
    ]
    private static let keypadKeys: Set<UInt16> = [
        0x41, 0x43, 0x45, 0x47, 0x4B, 0x4C, 0x4E, 0x51, 0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5B, 0x5C,
    ]

    /// HID usage (矢印キー)。
    public enum ArrowUsage {
        public static let right = 0x4F
        public static let left = 0x50
        public static let down = 0x51
        public static let up = 0x52
    }

    private static let table: [Int: UInt16] = [
        // A〜Z
        0x04: 0x00, 0x05: 0x0B, 0x06: 0x08, 0x07: 0x02, 0x08: 0x0E, 0x09: 0x03, 0x0A: 0x05, 0x0B: 0x04,
        0x0C: 0x22, 0x0D: 0x26, 0x0E: 0x28, 0x0F: 0x25, 0x10: 0x2E, 0x11: 0x2D, 0x12: 0x1F, 0x13: 0x23,
        0x14: 0x0C, 0x15: 0x0F, 0x16: 0x01, 0x17: 0x11, 0x18: 0x20, 0x19: 0x09, 0x1A: 0x0D, 0x1B: 0x07,
        0x1C: 0x10, 0x1D: 0x06,
        // 1〜9, 0
        0x1E: 0x12, 0x1F: 0x13, 0x20: 0x14, 0x21: 0x15, 0x22: 0x17, 0x23: 0x16, 0x24: 0x1A, 0x25: 0x1C,
        0x26: 0x19, 0x27: 0x1D,
        // Return, Escape, Backspace, Tab, Space
        0x28: 0x24, 0x29: 0x35, 0x2A: 0x33, 0x2B: 0x30, 0x2C: 0x31,
        // - = [ ] \ (非 US #) ; ' ` , . /
        0x2D: 0x1B, 0x2E: 0x18, 0x2F: 0x21, 0x30: 0x1E, 0x31: 0x2A, 0x32: 0x2A, 0x33: 0x29, 0x34: 0x27,
        0x35: 0x32, 0x36: 0x2B, 0x37: 0x2F, 0x38: 0x2C,
        // Caps Lock
        0x39: 0x39,
        // F1〜F12
        0x3A: 0x7A, 0x3B: 0x78, 0x3C: 0x63, 0x3D: 0x76, 0x3E: 0x60, 0x3F: 0x61, 0x40: 0x62, 0x41: 0x64,
        0x42: 0x65, 0x43: 0x6D, 0x44: 0x67, 0x45: 0x6F,
        // Insert (Mac では Help), Home, Page Up, Forward Delete, End, Page Down
        0x49: 0x72, 0x4A: 0x73, 0x4B: 0x74, 0x4C: 0x75, 0x4D: 0x77, 0x4E: 0x79,
        // → ← ↓ ↑
        0x4F: 0x7C, 0x50: 0x7B, 0x51: 0x7D, 0x52: 0x7E,
        // テンキー: Clear / * - + Enter 1〜9 0 . =
        0x53: 0x47, 0x54: 0x4B, 0x55: 0x43, 0x56: 0x4E, 0x57: 0x45, 0x58: 0x4C,
        0x59: 0x53, 0x5A: 0x54, 0x5B: 0x55, 0x5C: 0x56, 0x5D: 0x57, 0x5E: 0x58, 0x5F: 0x59, 0x60: 0x5B,
        0x61: 0x5C, 0x62: 0x52, 0x63: 0x41, 0x67: 0x51,
        // ISO の § キー
        0x64: 0x0A,
        // F13〜F20
        0x68: 0x69, 0x69: 0x6B, 0x6A: 0x71, 0x6B: 0x6A, 0x6C: 0x40, 0x6D: 0x4F, 0x6E: 0x50, 0x6F: 0x5A,
        // JIS キーボード: ろ, ¥, かな, 英数
        0x87: 0x5E, 0x89: 0x5D, 0x90: 0x68, 0x91: 0x66,
        // 左 Control/Shift/Option/Command, 右 Control/Shift/Option/Command
        0xE0: 0x3B, 0xE1: 0x38, 0xE2: 0x3A, 0xE3: 0x37, 0xE4: 0x3E, 0xE5: 0x3C, 0xE6: 0x3D, 0xE7: 0x36,
    ]
}
